const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const code = fs.readFileSync(__dirname + '/motion.js', 'utf8');
function setup(reduced = false, imageState = {}, paths = {}) {
  const baseURI = paths.baseURI || 'https://1bit.kr/';
  const gif = paths.gif || 'assets/wave.gif';
  const png = paths.png || 'assets/wave.png';
  const preference = {matches: reduced, addEventListener(_, fn) {this.change = fn;}};
  const source = {getAttribute: () => gif, removeAttribute(name) {this.removed = name;}};
  const img = {currentSrc: new URL(gif, baseURI).href, getAttribute: () => png, addEventListener(_, fn) {this.error = fn;}};
  Object.assign(img, imageState);
  const button = {hidden: true, addEventListener(_, fn) {this.click = fn;}, setAttribute(name, value) {this[name] = value;}};
  const classes = new Set();
  const figure = {classList: {add: value => classes.add(value)}, querySelector: selector => selector === 'source' ? source : selector === 'img' ? img : button};
  vm.runInNewContext(code, {URL, window: {matchMedia: () => preference}, document: {baseURI, querySelectorAll: () => [figure]}});
  return {preference, source, img, button, classes};
}
