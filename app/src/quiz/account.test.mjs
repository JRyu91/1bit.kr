// 실행: node src/quiz/account.test.mjs  (기존 quiz/account.test.cjs 의 시나리오를 새 클래스에 맞춘 것)
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const questions = require('../../../quiz/questions.json');
const storage = new Map();
Object.defineProperty(globalThis, 'localStorage', {configurable: true, value: {getItem: k => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, v)}});
globalThis.confirm = () => true;
const {QuizAccount, E, api, guestKey} = await import('./account.ts');

let changed;
const client = new QuizAccount(questions, state => { changed = state; });
assert.equal(client.canEdit(), false, 'login required before editing');
const users = new Map(); let session = 'alice';
client.api = async (path, body) => {
  if (path === '/account/me') return {ok: {id: session, name: session}};
  if (path === '/quiz/progress') {
    const cloud = users.get(session) || {revision: 0, state: null};
    if (!body) return {accountId: session, ...cloud};
    if (body.accountId !== session) throw Error('계정 변경');
    if (body.revision !== cloud.revision) throw Error('저장 충돌');
    users.set(session, {revision: cloud.revision + 1, state: body.state});
    return {revision: cloud.revision + 1};
  }
  if (path === '/account/logout') return {};
  throw Error('unexpected ' + path);
};
globalThis.fetch = async () => ({status: 409, ok: false, json: async () => ({err: '다른 기기에서 진도가 바뀌었어. 현재 진도를 백업한 뒤 서버 진도를 불러와 줘'})});
await assert.rejects(() => api('/quiz/progress', {}), error => error.status === 409 && error.message === '다른 기기에서 진도가 변경되었습니다. 현재 진도를 백업한 뒤 서버 진도를 불러오세요.');
const guest = E.fresh(); E.answer(guest, questions[0], ['A']);
storage.set(guestKey, JSON.stringify(guest));
assert.equal(Object.keys((await client.start(guest)).records).length, 0, 'guest never imported silently');
await client.importGuest(); await client.queue;
assert.equal(users.get('alice').state.records[1].correct, true);
const state = E.fresh(); E.answer(state, questions[1], ['A']);
client.save(state); state.current = 3; client.save(state); await client.queue;
assert.equal(users.get('alice').revision, 3);
assert.equal(users.get('alice').state.current, 3);
assert.equal(JSON.parse(storage.get(client.key)).pending, false);
users.get('alice').revision++;
state.current = 4; client.save(state); await client.queue;
assert.equal(client.paused, true);
assert.equal(users.get('alice').state.current, 3, 'conflict cannot overwrite cloud');
assert.equal(JSON.parse(storage.get(client.key)).state.current, 4, 'unsent record preserved');
await client.load({id: 'alice', name: 'alice'});
assert.equal(client.paused, true, 'reload detects unsent conflict');
await client.reload();
assert.equal(client.paused, false);
assert.equal(changed.current, 3);
session = 'bob'; await client.load({id: 'bob', name: 'bob'});
assert.equal(Object.keys(client.latest.records).length, 0, 'second account cannot inherit first');
client.save(guest); session = 'alice'; await client.queue;
assert.equal(client.paused, true, 'changed game cookie cannot redirect a queued save');
assert.equal(users.get('alice').state.current, 3);
assert.equal(JSON.parse(storage.get(guestKey)).records[1].correct, true, 'guest preserved');
await client.logout();
assert.equal(client.user, null);
assert.equal(client.canEdit(), false);
session = 'alice'; await client.load({id: 'alice', name: 'alice'}, true);
const previousApi = client.api;
client.api = async (path, body) => { if (path === '/quiz/progress' && body) { const error = Error('로그인 필요'); error.status = 401; throw error; } return previousApi(path, body); };
client.save(guest); await client.queue;
assert.equal(client.user, null, 'expired session requires login');
assert.equal(client.paused, true, 'expired session keeps backup reachable');
assert.equal(JSON.parse(storage.get(client.key)).pending, true, 'expired session keeps unsent progress');
client.api = previousApi;
const oldRecords = users.get('alice').state.records;
users.get('alice').state = {...users.get('alice').state, autoReview: 6};
const recovered = await client.load({id: 'alice', name: 'alice'}, true);
assert.equal(recovered.autoReview, undefined, 'old tab screen metadata repaired');
assert.deepEqual(recovered.records, oldRecords, 'old tab recovery preserves learning records');
client.onStorage({key: client.key});
assert.equal(client.canEdit(), false, 'another tab change pauses editing');
console.log('account sync queue / guest import / account isolation / conflict recovery / changed session PASS');
